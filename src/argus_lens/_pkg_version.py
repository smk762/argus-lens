"""The package version, robust to a source tree that was never built.

``_version.py`` is generated by hatch-vcs at build/install time and is
gitignored, so a bare checkout or a copied source tree (e.g. a CI or audit
sandbox that runs the tests without installing) doesn't have it. Fall back to
the installed distribution's metadata, then to a placeholder, instead of
failing ``import argus_lens``.
"""

from __future__ import annotations

try:
    from argus_lens._version import __version__
except ImportError:  # pragma: no cover - depends on how the tree was obtained
    from importlib.metadata import PackageNotFoundError, version

    try:
        __version__ = version("argus-lens")
    except PackageNotFoundError:
        __version__ = "0.0.0+unknown"

__all__ = ["__version__"]
